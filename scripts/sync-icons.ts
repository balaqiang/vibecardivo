/**
 * Extracts the brand icon paths Vibecard uses from `simple-icons` (CC0-1.0) into a small
 * generated module, so the runtime never loads the full 3k-icon package.
 * Run with `pnpm icons:sync` after adding a platform.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as icons from 'simple-icons';

/** platform id → simple-icons export name */
const MAP: Record<string, string> = {
  github: 'siGithub',
  gitlab: 'siGitlab',
  x: 'siX',
  instagram: 'siInstagram',
  youtube: 'siYoutube',
  tiktok: 'siTiktok',
  facebook: 'siFacebook',
  threads: 'siThreads',
  bluesky: 'siBluesky',
  mastodon: 'siMastodon',
  discord: 'siDiscord',
  telegram: 'siTelegram',
  whatsapp: 'siWhatsapp',
  dribbble: 'siDribbble',
  behance: 'siBehance',
  figma: 'siFigma',
  medium: 'siMedium',
  devto: 'siDevdotto',
  hashnode: 'siHashnode',
  substack: 'siSubstack',
  stackoverflow: 'siStackoverflow',
  leetcode: 'siLeetcode',
  kaggle: 'siKaggle',
  huggingface: 'siHuggingface',
  npm: 'siNpm',
  reddit: 'siReddit',
  twitch: 'siTwitch',
  spotify: 'siSpotify',
  steam: 'siSteam',
  kofi: 'siKofi',
  buymeacoffee: 'siBuymeacoffee',
  patreon: 'siPatreon',
  linktree: 'siLinktree',
  pinterest: 'siPinterest',
  producthunt: 'siProducthunt',
};

const lib = icons as unknown as Record<string, { path: string; hex: string } | undefined>;
const lines = Object.entries(MAP).map(([id, name]) => {
  const icon = lib[name];
  if (!icon) throw new Error(`simple-icons has no export named ${name}`);
  return `  ${id}: { path: '${icon.path}', brand: '#${icon.hex}' },`;
});

const out = `// Generated by scripts/sync-icons.ts from simple-icons (CC0-1.0). Do not edit by hand.
export const BRAND_ICONS = {
${lines.join('\n')}
} as const;
`;

const target = join(import.meta.dirname, '..', 'src', 'core', 'catalog', 'icons.generated.ts');
writeFileSync(target, out);
console.log(`✓ wrote ${Object.keys(MAP).length} icons to ${target}`);
